async (page) => {
 const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('cijian-web-quiz-trial-v1')));
 await page.getByRole('button',{name:'课后测验',exact:true}).click();
 await page.locator('#lesson-select').selectOption('U1L1');
 await page.getByRole('button',{name:'开始这课测验 →',exact:true}).click();
 const old=(await state()).session;
 const id=old.questions[old.index].wordId;
 const word=await page.evaluate(id=>window.CIJIAN_WORDS.find(w=>w.id===id).word,id);
 await page.getByRole('button',{name:'斩词',exact:true}).click();
 if(!(await state()).slain[id])throw Error('Slay not saved');
 await page.getByRole('button',{name:'撤销斩词',exact:true}).click();
 if((await state()).slain[id])throw Error('Undo failed');
 await page.getByRole('heading',{name:word,exact:true}).waitFor();
 await page.getByRole('button',{name:'☆ 收藏',exact:true}).click();
 await page.getByRole('button',{name:'斩词',exact:true}).click();
 await page.getByRole('button',{name:'取消',exact:true}).click();
 if((await state()).slain[id])throw Error('Cancel did not cancel');
 await page.getByRole('button',{name:'斩词',exact:true}).click();
 await page.getByRole('button',{name:'仍然斩词',exact:true}).click();
 await page.getByRole('button',{name:'← 保存退出',exact:true}).click();
 await page.getByRole('button',{name:'课后测验',exact:true}).click();
 await page.locator('#lesson-select').selectOption('U1L1');
 await page.getByRole('button',{name:'开始这课测验 →',exact:true}).click();
 if((await state()).session.questions.slice((await state()).session.index).some(q=>q.wordId===id))throw Error('Slain word leaked into pending quiz');
 await page.getByRole('button',{name:'← 保存退出',exact:true}).click();
 await page.getByRole('button',{name:'课后测验',exact:true}).click();
 await page.locator('#lesson-select').selectOption('U1L1');
 await page.locator('#include-slain').check();
 await page.getByRole('button',{name:'开始这课测验 →',exact:true}).click();
 if(!(await state()).session.questions.some(q=>q.wordId===id))throw Error('Opt-in inclusion failed');
 await page.getByRole('button',{name:'← 保存退出',exact:true}).click();
 await page.reload();
 if(!(await state()).slain[id])throw Error('Slay not persisted');
 await page.getByRole('button',{name:'薄弱词本',exact:true}).click();
 await page.getByRole('button',{name:/^已斩 \d+$/}).click();
 await page.getByText(word,{exact:true}).waitFor();
 await page.getByRole('button',{name:'抽查已斩词 →',exact:true}).click();
 await page.getByRole('heading',{name:word,exact:true}).waitFor();
 if(!(await state()).session.includeSlain)throw Error('Sampling not explicit');
 await page.getByRole('button',{name:'恢复复习',exact:true}).click();
 if((await state()).slain[id])throw Error('Restore failed');
 await page.getByRole('button',{name:'← 保存退出',exact:true}).click();
 console.log('PASS: slay/undo, favorite warning/cancel, default pending exclusion, opt-in inclusion, persistence, dedicated sampling, restore.');
}
